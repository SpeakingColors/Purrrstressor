#!/usr/bin/env python3
"""Generate src/editor/Layout.h from docs/mockups/layout.json (made by tools/dump_layout.py
from the mockup page). The native editor takes every position, size, label and tooltip from
the mockup this way, so the two cannot drift apart. Run from the repo root."""
import json
d = json.load(open('docs/mockups/layout.json'))
ox, oy = d['topAbs'][0], d['topAbs'][1]
col = {'var(--g)': 0, 'var(--y)': 1, 'var(--o)': 2, 'var(--r)': 3, 'var(--b)': 4}
top = d['top']
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
def f(v):
    t = '%g' % v
    if 'e' in t: t = '%.4f' % v
    return t + ('' if '.' in t else '.0') + 'f'
def rc(r): return '{ ' + ', '.join(f(v) for v in r) + ' }'
leds = [t for t in top if t['c'].startswith('led') and not t['c'].startswith('led-hit')]
hits = [t for t in top if t['c'] == 'led-hit']
pb = [t for t in top if t['c'] == 'pbtn']
texts = [t for t in top if t['c'] in ('lbl', 'sect', 'lnum')]
br = [t for t in top if t['c'] == 'bracket'][0]
assert len(leds) == 32 and len(hits) == 14 and len(pb) == 3, (len(leds), len(hits), len(pb))
o = []
o.append('// GENERATED by tools/gen_layout.py from docs/mockups/layout.json. Do not edit by hand.')
o.append('#pragma once')
o.append('namespace layout {')
o.append('struct Rc { float x, y, w, h; };')
o.append('struct Led { float cx, cy; int color; };          // color: 0 green, 1 yellow, 2 orange, 3 red, 4 blue')
o.append('struct Hit { Rc r; const char* tip; const char* name; };')
o.append('struct Txt { const char* s; Rc r; float size; bool ui; bool bold; float spacing; bool upper; bool title; };')
o.append('struct Btn { Rc r; const char* tip; };')
o.append('constexpr int W = 1200, H = 640;')
for k in ['cheekL', 'cheekR', 'hdr', 'body', 'top', 'disp', 'knobs', 'meters', 'foot', 'logo', 'name', 's87', 'pPrev', 'pName', 'pNext', 'pSave', 'bBypass', 'bGuide', 'bSettings', 'bAbout', 'cvCurve', 'cvFilt', 'cvHist', 'cvIn', 'cvOut', 'pkIn', 'pkOut', 'winsz']:
    if k == 'top': r = d['topAbs']
    else: r = d[k]
    o.append('constexpr Rc %s = %s;' % (k, rc(r)))
o.append('constexpr Rc bracket = %s;' % rc([br['x'] + ox, br['y'] + oy, br['w'], br['h']]))
def led(t): return '{ %s, %s, %d }' % (f(t['x'] + ox + t['w'] / 2), f(t['y'] + oy + t['h'] / 2), col[t['color']])
o.append('constexpr Led ladder[16] = { ' + ', '.join(led(t) for t in leds[0:16]) + ' };')
o.append('constexpr Led ratioLeds[8] = { ' + ', '.join(led(t) for t in leds[16:24]) + ' };')
o.append('constexpr Led thdLeds[2] = { ' + ', '.join(led(t) for t in leds[24:26]) + ' };')
o.append('constexpr const char* thdTips[2] = { ' + ', '.join(q(t['tip']) for t in leds[24:26]) + ' };')
o.append('constexpr Led detLeds[3] = { ' + ', '.join(led(t) for t in leds[26:29]) + ' };')
o.append('constexpr Led audLeds[3] = { ' + ', '.join(led(t) for t in leds[29:32]) + ' };')
def hit(t): return '{ %s, %s, %s }' % (rc([t['x'] + ox, t['y'] + oy, t['w'], t['h']]), q(t['tip']), q(t['aria']))
o.append('constexpr Hit ratioHits[8] = { ' + ', '.join(hit(t) for t in hits[0:8]) + ' };')
o.append('constexpr Hit detHits[3] = { ' + ', '.join(hit(t) for t in hits[8:11]) + ' };')
o.append('constexpr Hit audHits[3] = { ' + ', '.join(hit(t) for t in hits[11:14]) + ' };')
def btn(t): return '{ %s, %s }' % (rc([t['x'] + ox, t['y'] + oy, t['w'], t['h']]), q(t['tip']))
o.append('constexpr Btn plateBtns[3] = { ' + ', '.join(btn(t) for t in pb) + ' }; // ratio, detector, audio')
tx = []
for t in texts:
    size = float(t['fs'].replace('px', ''))
    ui = t['ff'] == 'ui'
    bold = int(t['fw']) >= 600
    sp = 0.0 if t['ls'] == 'normal' else float(t['ls'].replace('px', ''))
    upper = t['tt'] == 'uppercase'
    title = t['c'] in ('lbl', 'sect')
    tx.append('{ %s, %s, %s, %s, %s, %s, %s, %s }' % (q(t['t']), rc([t['x'] + ox, t['y'] + oy, t['w'], t['h']]), f(size), 'true' if ui else 'false', 'true' if bold else 'false', f(sp), 'true' if upper else 'false', 'true' if title else 'false'))
o.append('constexpr Txt plateTexts[%d] = {\n    ' % len(tx) + ',\n    '.join(tx) + ' };')
o.append('constexpr int numPlateTexts = %d;' % len(tx))
o.append('struct KnobCell { const char* name; Rc label; Rc knob; Rc value; };')
names = ['input', 'attack', 'release', 'output', 'headroom', 'mix']
cells = []
for n, c in zip(names, d['kcells']):
    k = c['knob'] or [0, 0, 0, 0]
    cells.append('{ %s, %s, %s, %s }' % (q(n), rc(c['labR']), rc(k), rc(c['val'])))
o.append('constexpr KnobCell cells[6] = { ' + ',\n    '.join(cells) + ' };')
o.append('constexpr Rc hrButton = %s;' % rc(d['kcells'][4]['btn']))
o.append('constexpr Rc dispCaps[3] = { ' + ', '.join(rc(c['r']) for c in d['caps']) + ' };')
o.append('constexpr const char* dispCapText[3] = { ' + ', '.join(q(c['t']) for c in d['caps']) + ' };')
o.append('constexpr Rc meterCaps[2] = { ' + ', '.join(rc(c['r']) for c in d['mcap']) + ' };')
o.append('constexpr Rc trimBtn = %s;' % rc(d['mbtn'][0]['r']))
o.append('constexpr Rc matchBtn = %s;' % rc(d['mbtn'][1]['r']))
o.append('} // namespace layout')
open('src/editor/Layout.h', 'w').write('\n'.join(o) + '\n')
print('ok', len(tx), 'texts')
